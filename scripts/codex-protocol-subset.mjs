// Usage: codex app-server generate-ts --out <temporary-dir>
// Then: node scripts/codex-protocol-subset.mjs <temporary-dir>
// Prints the generated subset for review; does not overwrite repository files.
import { existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const CODEX_PROTOCOL_ROOT_TYPES = [
  "InitializeParams",
  "v2/UserInput",
  "v2/TurnStartParams",
  "v2/ThreadResumeParams",
  "v2/AskForApproval",
  "v2/ToolRequestUserInputResponse",
  "v2/ThreadSetNameParams",
  "v2/ThreadGoalGetResponse",
  "v2/ThreadGoalSetParams",
  "v2/ThreadGoalSetResponse",
];

export function generateCodexProtocolSubset(generatedDirectory) {
  const root = resolve(generatedDirectory);
  const seen = new Set();
  const output = [
    "// Generated from the deployed Codex app-server TypeScript schema.",
    "// Regenerate with scripts/codex-protocol-subset.mjs; do not edit types by hand.",
  ];

  function visit(file) {
    if (seen.has(file)) return;
    seen.add(file);
    const source = readFileSync(file, "utf8");
    const imports = [...source.matchAll(/^import type .* from "([^"]+)";$/gm)];
    for (const match of imports) visit(resolve(dirname(file), `${match[1]}.ts`));
    output.push(source.replace(/^import type .*;\n/gm, "").replace(/^\/\/.*\n/gm, "").trim());
  }

  for (const type of CODEX_PROTOCOL_ROOT_TYPES) {
    const file = resolve(root, `${type}.ts`);
    if (!existsSync(file)) {
      throw new Error(`Missing expected Codex schema type: ${type}.ts`);
    }
    visit(file);
  }

  return `${output.join("\n\n")}\n`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (!process.argv[2]) {
    throw new Error("Pass the directory generated by codex app-server generate-ts");
  }
  process.stdout.write(generateCodexProtocolSubset(process.argv[2]));
}
